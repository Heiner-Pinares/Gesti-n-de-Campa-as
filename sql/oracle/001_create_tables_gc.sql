CREATE TABLE TBL_USUARIO_GC (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USUARIO VARCHAR2(80 CHAR) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(150 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR),
    CLAVE_HASH VARCHAR2(128 CHAR) NOT NULL,
    ROL VARCHAR2(20 CHAR) DEFAULT 'ANALISTA' NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    ULTIMO_ACCESO TIMESTAMP(6) WITH TIME ZONE,
    FECHA_CREACION TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO_GC PRIMARY KEY (ID_USUARIO),
    CONSTRAINT CK_USU_ROL_GC CHECK (ROL IN ('ADMINISTRADOR', 'ANALISTA')),
    CONSTRAINT CK_USU_ACT_GC CHECK (ACTIVO IN (0, 1))
);

CREATE UNIQUE INDEX UK_USUARIO_NORM_GC
    ON TBL_USUARIO_GC (UPPER(USUARIO));

CREATE TABLE TBL_CAMPANA_VERSION_GC (
    ID_VERSION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CAMPANA_ORIGEN NUMBER,
    VERSION NUMBER(6) DEFAULT 1 NOT NULL,
    COD_PLAN VARCHAR2(10 CHAR),
    NOMBRE_CAMPANA VARCHAR2(400 CHAR) NOT NULL,
    PLAN_MINIMO NUMBER(12,2),
    PLAN_MAXIMO NUMBER(12,2),
    ESCENARIO VARCHAR2(100 CHAR) NOT NULL,
    TIPO_BENEFICIO VARCHAR2(20 CHAR) NOT NULL,
    VALOR_BENEFICIO NUMBER(12,4) NOT NULL,
    PERIODO_MESES NUMBER(4),
    TIPO_FILTRO VARCHAR2(10 CHAR),
    DIA_INI NUMBER(2),
    DIA_FIN NUMBER(2),
    VIGENCIA_INI DATE NOT NULL,
    VIGENCIA_FIN DATE NOT NULL,
    ESTADO CHAR(1 CHAR) DEFAULT 'A' NOT NULL,
    DESCRIPCION VARCHAR2(400 CHAR),
    CONDICIONES_JSON CLOB,
    ID_USUARIO_CREACION NUMBER NOT NULL,
    FECHA_CREACION TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CAMPA_VER_GC PRIMARY KEY (ID_VERSION),
    CONSTRAINT UK_CAMPA_VER_GC UNIQUE (ID_CAMPANA_ORIGEN, VERSION),
    CONSTRAINT CK_CAMPA_BEN_GC CHECK (TIPO_BENEFICIO IN ('PORCENTAJE', 'MONTO_FIJO')),
    CONSTRAINT CK_CAMPA_EST_GC CHECK (ESTADO IN ('A', 'I')),
    CONSTRAINT CK_CAMPA_VIG_GC CHECK (VIGENCIA_FIN >= VIGENCIA_INI),
    CONSTRAINT FK_CAMPA_USU_GC FOREIGN KEY (ID_USUARIO_CREACION)
        REFERENCES TBL_USUARIO_GC (ID_USUARIO)
);

CREATE INDEX IDX_CAMPA_VIG_GC
    ON TBL_CAMPANA_VERSION_GC (ESTADO, VIGENCIA_INI, VIGENCIA_FIN);

CREATE INDEX IDX_CAMPA_NOM_GC
    ON TBL_CAMPANA_VERSION_GC (NOMBRE_CAMPANA, VERSION);

CREATE TABLE TBL_VALIDACION_EJECUCION_GC (
    ID_EJECUCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FECHA_DESDE DATE NOT NULL,
    FECHA_HASTA DATE NOT NULL,
    TIPO_EJECUCION VARCHAR2(15 CHAR) NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    PARAMETROS_JSON CLOB,
    TOTAL_EVALUADOS NUMBER(12) DEFAULT 0 NOT NULL,
    TOTAL_CORRECTOS NUMBER(12) DEFAULT 0 NOT NULL,
    TOTAL_ERRORES NUMBER(12) DEFAULT 0 NOT NULL,
    TOTAL_REVISAR NUMBER(12) DEFAULT 0 NOT NULL,
    TOTAL_NO_APLICA NUMBER(12) DEFAULT 0 NOT NULL,
    MENSAJE_ERROR VARCHAR2(1000 CHAR),
    ID_USUARIO_EJECUCION NUMBER,
    FECHA_SOLICITUD TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_INICIO TIMESTAMP(6) WITH TIME ZONE,
    FECHA_FIN TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_EJEC_GC PRIMARY KEY (ID_EJECUCION),
    CONSTRAINT CK_EJEC_TIPO_GC CHECK (TIPO_EJECUCION IN ('MANUAL', 'PROGRAMADA')),
    CONSTRAINT CK_EJEC_EST_GC CHECK (ESTADO IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA', 'ERROR')),
    CONSTRAINT CK_EJEC_FEC_GC CHECK (FECHA_HASTA >= FECHA_DESDE),
    CONSTRAINT FK_EJEC_USU_GC FOREIGN KEY (ID_USUARIO_EJECUCION)
        REFERENCES TBL_USUARIO_GC (ID_USUARIO)
);

CREATE INDEX IDX_EJEC_EST_GC
    ON TBL_VALIDACION_EJECUCION_GC (ESTADO, FECHA_SOLICITUD);

CREATE INDEX IDX_EJEC_FEC_GC
    ON TBL_VALIDACION_EJECUCION_GC (FECHA_DESDE, FECHA_HASTA);

CREATE TABLE TBL_VALIDACION_RESULTADO_GC (
    ID_RESULTADO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EJECUCION NUMBER NOT NULL,
    ID_VERSION NUMBER,
    INVOICE_ID NUMBER,
    INVOICING_DATE DATE,
    CO_ID NUMBER,
    LINEA VARCHAR2(30 CHAR),
    CH_REASON NUMBER,
    PLAN_MONTO NUMBER(12,2),
    DESCUENTO_ESPERADO NUMBER(12,2),
    DESCUENTO_APLICADO NUMBER(12,2),
    DIFERENCIA NUMBER(12,2),
    CLASIFICACION VARCHAR2(20 CHAR) NOT NULL,
    CODIGO_MOTIVO VARCHAR2(50 CHAR),
    DESCRIPCION_MOTIVO VARCHAR2(1000 CHAR) NOT NULL,
    EVIDENCIA_JSON CLOB,
    FECHA_REGISTRO TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESULT_GC PRIMARY KEY (ID_RESULTADO),
    CONSTRAINT CK_RES_EST_GC CHECK (CLASIFICACION IN ('CORRECTO', 'ERROR', 'POR_REVISAR', 'NO_APLICA')),
    CONSTRAINT FK_RES_EJEC_GC FOREIGN KEY (ID_EJECUCION)
        REFERENCES TBL_VALIDACION_EJECUCION_GC (ID_EJECUCION),
    CONSTRAINT FK_RES_VER_GC FOREIGN KEY (ID_VERSION)
        REFERENCES TBL_CAMPANA_VERSION_GC (ID_VERSION)
);

CREATE INDEX IDX_RES_EJE_EST_GC
    ON TBL_VALIDACION_RESULTADO_GC (ID_EJECUCION, CLASIFICACION);

CREATE INDEX IDX_RES_CO_FEC_GC
    ON TBL_VALIDACION_RESULTADO_GC (CO_ID, INVOICING_DATE);

CREATE TABLE TBL_AUDITORIA_CAMBIO_GC (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ENTIDAD VARCHAR2(50 CHAR) NOT NULL,
    ID_ENTIDAD NUMBER NOT NULL,
    ACCION VARCHAR2(20 CHAR) NOT NULL,
    VALOR_ANTERIOR_JSON CLOB,
    VALOR_NUEVO_JSON CLOB,
    ID_USUARIO NUMBER,
    DIRECCION_IP VARCHAR2(45 CHAR),
    FECHA_EVENTO TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_GC PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_AUD_ACC_GC CHECK (ACCION IN ('CREAR', 'ACTUALIZAR', 'ACTIVAR', 'DESACTIVAR', 'EJECUTAR')),
    CONSTRAINT FK_AUD_USU_GC FOREIGN KEY (ID_USUARIO)
        REFERENCES TBL_USUARIO_GC (ID_USUARIO)
);

CREATE INDEX IDX_AUD_ENT_GC
    ON TBL_AUDITORIA_CAMBIO_GC (ENTIDAD, ID_ENTIDAD, FECHA_EVENTO);

CREATE INDEX IDX_AUD_FEC_GC
    ON TBL_AUDITORIA_CAMBIO_GC (FECHA_EVENTO);
