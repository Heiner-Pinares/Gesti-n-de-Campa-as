SELECT
    T.INVOICE_ID,
    T.INVOICING_DATE,
    T.BILLSQNO,
    T.BILLING_MODE,
    T.CUSTOMER_ID,
    T.CO_ID,
    tfun001_get_dnnum_from_coid(T.CO_ID, T.INVOICING_DATE) LINEA,
    T.CH_SEQNO,
    T.CH_STATUS,
    T.CH_REASON,
    T.REASON,
    T.CH_VALIDFROM,
    T.PROD_OFFER,
    T.SNCODE,
    T.SERV_LONG_DES,
    T.SPCODE,
    T.SP_LONG_DES,
    T.CF_ADEL,
    T.CF_PRO,
    T.CF_DEV,
    T.Q_ADEL,
    T.Q_PRO,
    T.Q_DEV,
    T.MONTO_CON_IGV,
    D.PROD_OFFER,
    D.SNCODE,
    D.SERV_LONG_DES,
    D.SPCODE,
    D.SERV_LONG_DES,
    D.PROD_OFFER,
    D.CF_ADEL,
    D.CF_PRO,
    D.CF_DEV,
    D.MONTO_CON_IGV,
    D.Q_ADEL,
    D.Q_PRO,
    D.Q_DEV,
    CH.CH_SEQNO,
    CH.CH_STATUS,
    CH.CH_REASON,
    RA.RS_DESC MOTIVO_ALTA,
    CH.CH_VALIDFROM,
    P.VALOR,
    P.VALIDO_DESDE,
    CASE
        WHEN P.VALOR IN (
            'PROMOCION PORTABILIDAD PRESENCIAL',
            'PORTABILIDAD PRESENCIAL CADENAS',
            'DTO PORTABILIDAD POSTPAGO',
            'PORTABILIDAD TELEVENTAS'
        ) AND T.CF_ADEL >= 69.90 AND T.CF_ADEL < 290 THEN 'X'
        WHEN P.VALOR IN ('PORTA ADICIONAL CON DTO', 'ADICIONAL CON DTO') THEN 'Y'
        WHEN P.VALOR = 'PROMO MIGRA PRE A POST'
             AND T.CF_ADEL = 29.90 AND CH.CH_REASON = 21 THEN 'Z'
        WHEN P.VALOR = 'PROMO MIGRA PRE A POST'
             AND T.CF_ADEL >= 39.90 AND T.CF_ADEL < 50
             AND CH.CH_REASON = 21 THEN 'K'
    END TIPO,
    CASE
        WHEN P.VALOR = 'PROMO MIGRA PRE A POST'
             AND T.CF_ADEL = 29.90
             AND CH.CH_REASON = 21
             AND D.CF_ADEL = -10
            THEN 'OK CAMPAÑA ' || P.VALOR
        WHEN P.VALOR = 'PROMO MIGRA PRE A POST'
             AND T.CF_ADEL >= 39.90 AND T.CF_ADEL < 50
             AND ((T.CF_ADEL * 0.3) + D.CF_ADEL) = 0
             AND CH.CH_REASON = 21
            THEN 'OK CAMPAÑA ' || P.VALOR
        WHEN P.VALOR IN (
            'PROMOCION PORTABILIDAD PRESENCIAL',
            'PORTABILIDAD PRESENCIAL CADENAS',
            'DTO PORTABILIDAD POSTPAGO',
            'PORTABILIDAD TELEVENTAS'
        ) AND CH.CH_REASON = 2002
          AND T.CF_ADEL >= 69.90 AND T.CF_ADEL < 290
          AND (T.CF_ADEL * 0.5 + D.CF_ADEL) = 0
            THEN 'OK CAMPAÑA ' || P.VALOR
        WHEN P.VALOR IN (
            'PROMOCION PORTABILIDAD PRESENCIAL',
            'PORTABILIDAD PRESENCIAL CADENAS',
            'DTO PORTABILIDAD POSTPAGO',
            'PORTABILIDAD TELEVENTAS'
        ) AND CH.CH_REASON = 2002
          AND T.CF_ADEL >= 69.90 AND T.CF_ADEL < 290
          AND D.SNCODE IS NULL
            THEN 'ERROR TIENE DESCUENTO'
        WHEN P.VALOR IN ('PORTA ADICIONAL CON DTO', 'ADICIONAL CON DTO')
             AND T.CF_ADEL IN (79.90, 95.90)
             AND CH.CH_REASON IN (2001, 2002)
             AND D.SNCODE IS NOT NULL
            THEN 'OK CAMPAÑA ' || P.VALOR
        WHEN P.VALOR IN ('PORTA ADICIONAL CON DTO', 'ADICIONAL CON DTO')
             AND T.CF_ADEL IN (79.90, 95.90)
             AND CH.CH_REASON IN (2001, 2002)
             AND D.SNCODE IS NULL
            THEN 'ERROR TIENE DESCUENTO'
        WHEN P.VALOR = 'PROMO MIGRA PRE A POST'
             AND T.CF_ADEL = 29.90
             AND CH.CH_REASON = 21
             AND NVL(D.CF_ADEL, 0) <> -10
            THEN 'ERROR DESCUENTO DE 10 SOLES'
    END VALIDACION
FROM USRVALCBIO.BASE_CF_BASICO_X T
INNER JOIN ODSCLARO.CONTRACT_HISTORY CH
    ON T.CO_ID = CH.CO_ID
INNER JOIN ODSCLARO.REASONSTATUS_ALL RA
    ON CH.CH_REASON = RA.RS_ID
LEFT JOIN BASE_FINAL_CAMPANA_HIST P
    ON T.CO_ID = P.CO_ID
   AND T.INVOICING_DATE = P.EMISION
LEFT JOIN (
    SELECT *
    FROM USRVALCBIO.BASE_CF_DESCUENTO_X L
    WHERE L.SPCODE NOT IN (3674)
) D
    ON T.CO_ID = D.CO_ID
   AND T.INVOICING_DATE = D.INVOICING_DATE
WHERE CH.CH_SEQNO = 2
  AND CH.CH_VALIDFROM >= '24/10/2026'
  AND CH.CH_VALIDFROM < '28/10/2026'
  AND CH.CH_REASON IN (21, 2001, 2002)
  AND T.CH_STATUS = 'a';
